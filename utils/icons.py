def get_lucide_svg(name: str, size: int = 20, color: str = "currentColor", stroke_width: float = 1.75, class_name: str = "") -> str:
    """
    Renders an inline Lucide SVG string with consistent dimensions and stroke width.
    """
    inner_svg = LUCIDE_ICONS.get(name)
    if not inner_svg:
        inner_svg = LUCIDE_ICONS.get("info", "")

    cls_attr = f' class="lucide lucide-{name} {class_name}"' if class_name else f' class="lucide lucide-{name}"'
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" '
        f'viewBox="0 0 24 24" fill="none" stroke="{color}" stroke-width="{stroke_width}" '
        f'stroke-linecap="round" stroke-linejoin="round"{cls_attr} style="vertical-align: middle; display: inline-block;">'
        f'{inner_svg}'
        f'</svg>'
    )

def get_lucide_data_uri(name: str, size: int = 36, color: str = "#1E3E62", bg_color: str = "#F1F5F9", stroke_width: float = 1.75) -> str:
    """
    Generates a high-resolution base64 data URI for Streamlit avatar images or badges.
    """
    inner_svg = LUCIDE_ICONS.get(name, LUCIDE_ICONS["info"])
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 24 24">'
        f'<rect width="24" height="24" rx="6" fill="{bg_color}"/>'
        f'<g fill="none" stroke="{color}" stroke-width="{stroke_width}" stroke-linecap="round" stroke-linejoin="round">'
        f'{inner_svg}'
        f'</g>'
        f'</svg>'
    )
    b64 = base64.b64encode(svg.encode("utf-8")).decode("utf-8")
    return f"data:image/svg+xml;base64,{b64}"

